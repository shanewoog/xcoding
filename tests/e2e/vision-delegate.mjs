import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { createServer } from "node:http";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const fixtureRoot = resolve(repositoryRoot, "tests/e2e/fixtures/read-only-agent");
const binaryName = process.platform === "win32" ? "xcoding-server.exe" : "xcoding-server";
const serverPath = resolve(repositoryRoot, "target/debug", binaryName);

// 1x1 transparent PNG. Content does not matter; the delegate provider is mocked.
const PNG_BASE64 =
  "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAAC0lEQVR4nGMAAQAABQABDQottAAAAABJRU5ErkJggg==";
const DELEGATE_MODEL = "mock-vision-model";
const VISION_DESCRIPTION = "Image 1: a login form with the error text INVALID_API_KEY.";

async function main() {
  await assertDelegateReplacesImagesAndCachesTheDescription();
  await assertVisionCapableModelKeepsReceivingImages();
  await assertDelegateFailureDegradesInsteadOfAborting();
  console.log("Vision delegate E2E passed.");
}

/// Session model has no vision support, so the attachment must reach the
/// delegate endpoint and only its description may reach the session model.
async function assertDelegateReplacesImagesAndCachesTheDescription() {
  const vision = await startMockProvider({ text: VISION_DESCRIPTION });
  const session = await startMockProvider({ text: "Acknowledged." });
  const context = await startIsolatedServer({
    slug: "vision-delegate",
    sessionBaseUrl: session.baseUrl,
    visionBaseUrl: vision.baseUrl,
  });

  try {
    const first = await context.rpc.request("session.chat", {
      workspace_root: fixtureRoot,
      message: "Why does this screen fail?",
      model: "fixture-model",
      images: [{ mime_type: "image/png", data_base64: PNG_BASE64, name: "screen.png" }],
    });
    assert.equal(first.session.status, "done");

    assert.equal(vision.requests.length, 1, "the delegate provider should be called once");
    const visionRequest = vision.requests[0];
    assert.equal(visionRequest.model, DELEGATE_MODEL);
    assert.equal(visionRequest.messages[0].role, "system");
    const visionParts = visionRequest.messages.at(-1).content;
    assert.ok(Array.isArray(visionParts), "the delegate must receive multi-part content");
    const imageParts = visionParts.filter((part) => part.type === "image_url");
    assert.equal(imageParts.length, 1, "the delegate must receive the attachment");
    assert.ok(
      imageParts[0].image_url.url.startsWith(`data:image/png;base64,${PNG_BASE64.slice(0, 24)}`),
      "the delegate must receive the original base64 payload",
    );

    assert.equal(session.requests.length, 1);
    assertNoImagePartsReachedTheSessionModel(session.requests[0]);
    const firstUserMessage = lastUserMessage(session.requests[0]);
    assert.match(firstUserMessage.content, /Why does this screen fail\?/);
    assert.match(firstUserMessage.content, /image description generated by mock-vision-model/);
    assert.match(firstUserMessage.content, /INVALID_API_KEY/);

    const started = context.rpc.events.filter((event) => event.type === "vision_delegate_start");
    const succeeded = context.rpc.events.filter((event) => event.type === "vision_delegate_success");
    assert.equal(started.length, 1);
    assert.equal(started[0].image_count, 1);
    assert.equal(started[0].delegate_model, DELEGATE_MODEL);
    assert.equal(succeeded.length, 1);
    assert.equal(succeeded[0].image_count, 1);
    assert.equal(succeeded[0].description_length, VISION_DESCRIPTION.length);
    assert.equal(
      context.rpc.events.filter((event) => event.type === "vision_delegate_failed").length,
      0,
    );

    // The stored transcript keeps the original attachment so Desktop can still
    // render the thumbnail after the delegate ran.
    const { detail } = await context.rpc.request("session.detail", {
      session_id: first.session.id,
    });
    const storedUser = detail.messages.find((message) => message.role === "user");
    assert.match(storedUser.content, /<!-- xcoding-images:image\/png\|/);
    assert.ok(
      detail.events.some((item) => item.event.type === "vision_delegate_success"),
      "delegate events must be persisted for replay",
    );

    // Second turn rebuilds provider messages from the same stored history. The
    // description cache must keep that from re-billing the delegate provider.
    const second = await context.rpc.request("session.chat", {
      workspace_root: fixtureRoot,
      message: "And what should I check first?",
      model: "fixture-model",
      session_id: first.session.id,
    });
    assert.equal(second.session.status, "done");
    assert.equal(vision.requests.length, 1, "a cached description must not call the delegate again");
    assert.equal(session.requests.length, 2);
    assertNoImagePartsReachedTheSessionModel(session.requests[1]);
    assert.ok(
      session.requests[1].messages.some(
        (message) => message.role === "user" && /INVALID_API_KEY/.test(contentText(message)),
      ),
      "the replayed turn should still carry the description",
    );
    assert.equal(
      context.rpc.events.filter((event) => event.type === "vision_delegate_start").length,
      1,
      "a cache hit must stay out of the activity feed",
    );
  } finally {
    await context.close();
    await vision.close();
    await session.close();
  }
}

/// A vision-capable session model must keep receiving the raw attachment even
/// while delegation is enabled, so no existing setup regresses.
async function assertVisionCapableModelKeepsReceivingImages() {
  const vision = await startMockProvider({ text: VISION_DESCRIPTION });
  const session = await startMockProvider({ text: "I can see it." });
  const context = await startIsolatedServer({
    slug: "vision-passthrough",
    sessionBaseUrl: session.baseUrl,
    visionBaseUrl: vision.baseUrl,
  });

  try {
    const result = await context.rpc.request("session.chat", {
      workspace_root: fixtureRoot,
      message: "Read this screenshot",
      model: "gpt-4o-mock",
      images: [{ mime_type: "image/png", data_base64: PNG_BASE64, name: "screen.png" }],
    });
    assert.equal(result.session.status, "done");

    assert.equal(vision.requests.length, 0, "vision-capable models must not use the delegate");
    assert.equal(session.requests.length, 1);
    const parts = lastUserMessage(session.requests[0]).content;
    assert.ok(Array.isArray(parts), "the session model should receive multi-part content");
    assert.equal(parts.filter((part) => part.type === "image_url").length, 1);
    assert.equal(
      context.rpc.events.filter((event) => event.type.startsWith("vision_delegate")).length,
      0,
    );
  } finally {
    await context.close();
    await vision.close();
    await session.close();
  }
}

/// A delegate outage must degrade the one attachment to a note and let the turn
/// finish, instead of failing the session.
async function assertDelegateFailureDegradesInsteadOfAborting() {
  const vision = await startMockProvider({ status: 500, body: { message: "vision is down" } });
  const session = await startMockProvider({ text: "Continuing without the image." });
  const context = await startIsolatedServer({
    slug: "vision-failure",
    sessionBaseUrl: session.baseUrl,
    visionBaseUrl: vision.baseUrl,
  });

  try {
    const result = await context.rpc.request("session.chat", {
      workspace_root: fixtureRoot,
      message: "Look at this",
      model: "fixture-model",
      images: [{ mime_type: "image/png", data_base64: PNG_BASE64, name: "screen.png" }],
    });

    assert.equal(result.session.status, "done", "a delegate failure must not fail the session");
    assert.ok(vision.requests.length >= 1, "the delegate should have been attempted");
    assert.equal(session.requests.length, 1);
    assertNoImagePartsReachedTheSessionModel(session.requests[0]);
    assert.match(
      lastUserMessage(session.requests[0]).content,
      /1 image attachment\(s\) could not be described/,
    );

    const failed = context.rpc.events.filter((event) => event.type === "vision_delegate_failed");
    assert.equal(failed.length, 1);
    assert.equal(failed[0].image_count, 1);
    assert.match(failed[0].error, /chat\/completions/, "the failure should name the delegate endpoint");
    assert.equal(
      context.rpc.events.filter((event) => event.type === "error").length,
      0,
      "a degraded attachment is not a terminal session error",
    );
  } finally {
    await context.close();
    await vision.close();
    await session.close();
  }
}

function contentText(message) {
  if (typeof message.content === "string") {
    return message.content;
  }
  if (!Array.isArray(message.content)) {
    return "";
  }
  return message.content
    .filter((part) => part.type === "text")
    .map((part) => part.text)
    .join("\n");
}

function lastUserMessage(request) {
  const users = request.messages.filter((message) => message.role === "user");
  assert.ok(users.length > 0, "expected at least one user message");
  return users.at(-1);
}

function assertNoImagePartsReachedTheSessionModel(request) {
  for (const message of request.messages) {
    if (!Array.isArray(message.content)) {
      continue;
    }
    assert.equal(
      message.content.filter((part) => part.type === "image_url").length,
      0,
      "a delegated turn must not send image parts to the session model",
    );
  }
  const serialized = JSON.stringify(request);
  assert.ok(
    !serialized.includes(PNG_BASE64),
    "a delegated turn must not leak the base64 payload to the session model",
  );
}

async function startIsolatedServer({ slug, sessionBaseUrl, visionBaseUrl }) {
  const databaseDirectory = await mkdtemp(resolve(tmpdir(), `xcoding-e2e-${slug}-`));
  const homeDirectory = await mkdtemp(resolve(tmpdir(), `xcoding-e2e-${slug}-home-`));
  const configDirectory = resolve(homeDirectory, ".xcoding");
  await mkdir(configDirectory, { recursive: true });
  await writeFile(
    resolve(configDirectory, "config.json"),
    `${JSON.stringify(
      {
        max_provider_retries: 0,
        provider_fallback_enabled: false,
        base_url: sessionBaseUrl,
        api_key: "e2e-session-key",
        providers: [
          { id: "default", name: "openai", base_url: sessionBaseUrl, api_key: "e2e-session-key" },
          { id: "vision", name: "vision", base_url: visionBaseUrl, api_key: "e2e-vision-key" },
        ],
        active_provider_id: "default",
        vision_delegate: {
          enabled: true,
          provider_id: "vision",
          model: DELEGATE_MODEL,
          timeout_seconds: 30,
        },
        model_capabilities: { "fixture-model": { supports_vision: false } },
      },
      null,
      2,
    )}\n`,
    "utf8",
  );

  const rpc = startRpcClient({
    databasePath: resolve(databaseDirectory, "xcoding.db"),
    environment: {
      ...process.env,
      OPENAI_API_KEY: "e2e-session-key",
      XCODING_OPENAI_BASE_URL: sessionBaseUrl,
      HOME: homeDirectory,
      USERPROFILE: homeDirectory,
    },
  });

  return {
    rpc,
    close: async () => {
      await rpc.close();
      await rm(databaseDirectory, { recursive: true, force: true });
      await rm(homeDirectory, { recursive: true, force: true });
    },
  };
}

function startRpcClient({ databasePath, environment }) {
  const child = spawn(serverPath, ["--db", databasePath], {
    cwd: repositoryRoot,
    env: environment,
    stdio: ["pipe", "pipe", "pipe"],
    windowsHide: true,
  });
  const events = [];
  let outputBuffer = "";
  let diagnostics = "";
  let requestId = 0;
  const pending = new Map();

  child.stdout.setEncoding("utf8");
  child.stdout.on("data", (chunk) => {
    outputBuffer += chunk;
    let newlineIndex = outputBuffer.indexOf("\n");
    while (newlineIndex >= 0) {
      const line = outputBuffer.slice(0, newlineIndex).trim();
      outputBuffer = outputBuffer.slice(newlineIndex + 1);
      newlineIndex = outputBuffer.indexOf("\n");
      if (!line) {
        continue;
      }
      const message = JSON.parse(line);
      if (message.method === "session.event") {
        events.push(message.params);
        continue;
      }
      const request = pending.get(message.id);
      if (!request) {
        continue;
      }
      pending.delete(message.id);
      if (message.error) {
        request.reject(new Error(`RPC ${message.error.code}: ${message.error.message}`));
      } else {
        request.resolve(message.result);
      }
    }
  });
  child.stderr.setEncoding("utf8");
  child.stderr.on("data", (chunk) => {
    diagnostics += chunk;
  });
  child.once("error", (error) => rejectPending(error));
  child.once("exit", (code) => {
    if (pending.size > 0) {
      rejectPending(new Error(`xcoding-server exited with ${code}: ${diagnostics.trim()}`));
    }
  });

  function rejectPending(error) {
    for (const { reject } of pending.values()) {
      reject(error);
    }
    pending.clear();
  }

  return {
    events,
    request(method, params) {
      const id = ++requestId;
      const payload = JSON.stringify({ jsonrpc: "2.0", id, method, params });
      return new Promise((resolveRequest, rejectRequest) => {
        pending.set(id, { resolve: resolveRequest, reject: rejectRequest });
        child.stdin.write(`${payload}\n`);
      });
    },
    close() {
      return new Promise((resolveClose) => {
        child.once("exit", () => resolveClose());
        if (!child.killed) {
          child.kill();
        }
      });
    },
  };
}

/// Minimal OpenAI-compatible mock. Streams one text delta, or fails with the
/// given status when `status` is set.
async function startMockProvider({ text, status, body }) {
  const requests = [];
  const server = createServer(async (request, response) => {
    const chunks = [];
    for await (const chunk of request) {
      chunks.push(chunk);
    }
    requests.push(JSON.parse(Buffer.concat(chunks).toString("utf8")));
    if (status) {
      response.writeHead(status, { "content-type": "application/json" });
      response.end(JSON.stringify(body ?? { message: "mock failure" }));
      return;
    }
    response.writeHead(200, { "content-type": "text/event-stream" });
    response.write(`data: ${JSON.stringify({ choices: [{ delta: { content: text } }] })}\n\n`);
    response.end("data: [DONE]\n\n");
  });

  await new Promise((resolveListen, rejectListen) => {
    server.once("error", rejectListen);
    server.listen(0, "127.0.0.1", resolveListen);
  });
  const address = server.address();
  assert.ok(address && typeof address !== "string");

  return {
    baseUrl: `http://127.0.0.1:${address.port}/v1`,
    requests,
    close: () =>
      new Promise((resolveClose, rejectClose) =>
        server.close((error) => (error ? rejectClose(error) : resolveClose())),
      ),
  };
}

main().catch((error) => {
  console.error(error instanceof Error ? error.stack : String(error));
  process.exitCode = 1;
});
